export function resolvePalette(id) {
  const palette = palettes[id];
  const roles = Object.fromEntries(
    Object.entries(supportingRoles).map(([role, [baseColor, fallback]]) => [
      role, id === DEFAULT_PALETTE || !fallback ? baseColor : palette[fallback],
    ]),
  );
  return { ...palette, ...roles };
}
