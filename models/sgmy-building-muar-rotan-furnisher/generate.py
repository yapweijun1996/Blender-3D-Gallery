def chair(cx,cy,z,angle):
    """Rattan peacock chair. The radiating open back is bent cane, not a texture."""
    with frame(cx,cy,angle,z):
        s='Bent cane furniture'; mat=SUN
        for x in (-.25,.25):
            for y in (-.24,.24): rod(s,TIM,(x*1.12,y*1.12,0),(x,y,.49),.032,8)
        pole(s,SEC,0,0,.46,.087,.375,24)
        # Outline from the back of the seat to its wide fan crown and back down.
        arc=[]
        for i in range(31):
            a=math.radians(-47+274*i/30); arc.append((.55*math.cos(a),.26+.12*math.sin(a),1.00+.59*math.sin(a)))
        for a,b in zip(arc,arc[1:]): rod(s,mat,a,b,.035,8)
