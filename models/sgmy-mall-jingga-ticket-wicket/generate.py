        return [(-w/2,back)]+[(-w/2+r+r*math.cos(a),-d/2+r+r*math.sin(a)) for a in [PI+PI*i/24 for i in range(13)]]+[(w/2-r+r*math.cos(a),-d/2+r+r*math.sin(a)) for a in [1.5*PI+PI*i/24 for i in range(13)]]+[(w/2,back)]
