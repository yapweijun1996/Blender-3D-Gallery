def canopy(x,y,z,w,d,rise,mat):
    s='Raking concrete plates'; profile=[(x-w/2,z),(x+w/2,z+rise),(x+w/2,z+rise+.24),(x-w/2,z+.24)]
    prism(s,mat,profile,y-d/2,y+d/2)
    # Dark reglet divides the weather cap from the white exposed slab edge.
    prism(s,DARK,[(xx,zz+.215) for xx,zz in profile[:2]]+[(xx,zz+.25) for xx,zz in reversed(profile[:2])],y-d/2-.012,y+d/2+.012)


def screen(x,y,z,cols,rows):
    s='Sunburst breeze-block screen'; r=.245; pitch=.53
    for j in range(rows):
        for i in range(cols):
            u=x+(i-(cols-1)/2)*pitch; v=z+(j+.5)*pitch
            # Square-to-circle masonry unit, each with a real opening.
            pts=[]; fs=[]; n=16
            for yy,outer in ((y-.12,True),(y-.12,False),(y+.12,False),(y+.12,True)):
                for k in range(n):
                    a=TAU*k/n; co,si=math.cos(a),math.sin(a); rr=(pitch/2-.007)/max(abs(co),abs(si)) if outer else r*.78
                    pts.append((u+rr*co,yy,v+rr*si))
            for b in range(4):
                for k in range(n):fs.append((b*n+k,b*n+(k+1)%n,((b+1)%4)*n+(k+1)%n,((b+1)%4)*n+k))
            add(s,WALL,pts,fs)


