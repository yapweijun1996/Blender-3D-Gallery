def xy_plate(name,key,profile,z,thick,r=.012):
    n=len(profile); v=[(x,y,z+dz) for dz in (0,thick) for x,y in profile]
    return bevel(mesh(name,v,[tuple(range(n)),tuple(range(n,n*2))]+[(i,(i+1)%n,(i+1)%n+n,i+n) for i in range(n)],key,recalc=True),r)


