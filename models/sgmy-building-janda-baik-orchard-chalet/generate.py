def build():
    palette('ae764d','496e60','a56a42','485f61','6b4834'); s='Orchard chalet'; r='Twin folded roof planes'; f='Espalier glazing'; a='Outdoor dining deck'
    w,d=8.8,9.60; ridge=8.35; eave=.83; base=.62; front=-4.38
    for xx in (-3.85,0,3.85):
        for yy in (-6.03,-2.0,1.82,4.29): B(a,PAVE,xx,yy,0,.45,.45,base,.038)
    B(a,TIM,0,-.77,.44,8.67,11.70,.18,.019)
    for i in range(32): B(a,WALL,(i-15.5)*.267,-5.44,.621,.254,2.33,.056)
    # A true recessed glazed gable under planked soffits, not a solid roof prism.
    prism(s,TIM,[(-4.18,base),(0,8.12),(4.18,base)],front,4.41)
    for side in (-1,1):
        X=side*w/2; roof=[(X,eave),(0,ridge),(0,ridge+.22),(X+side*.18,eave+.04)]
        prism(r,ROOF,roof,-5.37,5.08)
        for i in range(28):
            yy=-5.36+i*10.43/27
            rod(r,ROOF,(X+side*.15,yy,eave+.094),(0,yy,ridge+.24),.042,7)
        for yy in (-5.40,5.10): beam(r,WALL,(X,yy,eave),(0,yy,ridge+.13),.22,.19)
        for i in range(1,9):
            k=i/9; x=X*(1-k); z=eave+(ridge-eave)*k-.035
            B(r,TIM,x,-4.88,z,.09,1.04,.095)
    rod(r,METAL,(0,-5.48,ridge+.23),(0,5.15,ridge+.23),.105,12)
    for yy in (front-.04,4.46):
        # Individually glazed truncated triangles and trapezoids follow the roof line.
        for j in range(8):
            x1=(j-4)*.91+.035; x2=(j-3)*.91-.035
            h1=7.81-abs(x1)*1.76; h2=7.81-abs(x2)*1.76
            for k,(lo,hi) in enumerate(((.76,2.94),(3.09,4.62),(4.76,7.83))):
                if min(h1,h2)<=lo+.01 and max(h1,h2)<=lo+.01: continue
                u=x1; v=x2
                if h1<lo: u=x1+(lo-h1)/(h2-h1)*(x2-x1)+.003
                if h2<lo: v=x1+(lo-h1)/(h2-h1)*(x2-x1)-.003
                poly=[(u,lo),(v,lo),(v,min(hi,7.81-abs(v)*1.76)),(u,min(hi,7.81-abs(u)*1.76))]
                prism(f,GLASS[(j//2+k)%3],poly,yy-.036,yy+.036)
        for z in (2.98,4.66): B(f,WALL,0,yy,z,(7.81-z)/1.76*2,.11,.10)
