    h=2.89;n=7;z0=3.26;top=z0+h*n;B(s,PAVE,0,0,0,36.29,12.32,.22,.07)
    B(s,SEC,0,1.09,.22,6.23,7.23,top-.22+1.68,.06)
    for a in (-1,1):
        x=a*10.31
        for xx in (-5.88,0,5.88):
            for y in (-3.52,3.55):B(s,SNOW,x+xx,y,.22,.60,.72,3.05,.033)
        B(s,WALL,x,0,z0,14.39,9.41,n*h)
        for k in range(n):
            z=z0+k*h
            B(s,SNOW,x,-.25,z,14.52,9.99,.20,.024)
            for j in (-1,0,1):
                xx=x+4.66*j;win(xx,-4.705,z+.81,3.29,1.48,3,k+j)
                B(s,SEC,xx,-4.84,z+.55,3.52,.39,.21,.023)
