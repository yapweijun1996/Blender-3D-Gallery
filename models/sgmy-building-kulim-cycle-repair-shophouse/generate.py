def rounded(x0,x1,y0,y1,r):
    pts=[(x0,y0)]
    for j in range(13):
        a=math.radians(-90+90*j/12); pts.append((x1-r+r*math.cos(a),y0+r+r*math.sin(a)))
    return pts+[(x1,y1),(x0,y1)]


def bicycle(x,y,z,scale):
    s='Cycle trade display'
    def p(u,v,d=0): return (x+u*scale,y+d*scale,z+v*scale)
    for u in (-.57,.57):
        archband(s,DARK,x+u*scale,y-.055*scale,z+.365*scale,.33*scale,.33*scale,.055*scale,.075*scale,0,360,32)
        for i in range(8):
            a=math.pi*i/8; u1=.32*math.cos(a); v1=.32*math.sin(a)
            beam(s,METAL,p(u-u1,.365-v1),p(u+u1,.365+v1),.017*scale)
    for a,b in (((-.57,.365),(-.17,.82)),((-.57,.365),(0,.34)),((-.17,.82),(0,.34)),((-.17,.82),(.36,.84)),((0,.34),(.36,.84)),((.36,.84),(.57,.365)),((.36,.84),(.31,1.02)),((.31,1.02),(.49,1.04)),((-.17,.82),(-.22,.98))):
        beam(s,ACC,p(*a,-.07),p(*b,-.07),.046*scale,.042*scale)
    B(s,TIM,x-.22*scale,y-.07*scale,z+.95*scale,.28*scale,.13*scale,.077*scale,.02)


