def terrace_tree(x,y,z,k):
    s='Setback pocket gardens';turn(s,SNOW,x,y,[(z,k*.79),(z+k*.65,k*.94),(z+k*.76,k*.94)],18)
    rod(s,TIM,(x,y,z+k*.72),(x,y,z+k*2.4),.115*k,9,.60)
    for j in range(7):
        a=j*2.4;ex=x+.71*k*math.cos(a);ey=y+.71*k*math.sin(a);ez=z+(1.86+.21*(j%3))*k
        rod(s,TIM,(x,y,z+1.34*k),(ex,ey,ez),.069*k,7,.5)
        turn(s,[LEAF,MOSS,FERN][j%3],ex,ey,[(ez,.33*k),(ez+.33*k,.85*k),(ez+.64*k,.64*k),(ez+.84*k,.22*k)],9)

def build():
    palette('dfd6bc','48776e','bc7150','637775','826144');s='Residential tiers';b='Recessed loggias'
    B(s,PAVE,0,0,0,30.6,15.6,.26,.11);B(s,SEC,0,.15,.26,27.8,12.12,3.62,.10)
    for x in (-12,-7,-2,3,8,12):win(x,-5.91,.62,2.93,2.65,3,round(x))
    B(s,ACC,-1,-6.62,3.03,8.30,3.47,.34,.10)
    for x in (-4.55,2.55):rod(s,SEC,(x,-7.56,.26),(x,-7.56,3.03),.17,12)
    label('TANJONG   LAPIS',-1,-8.365,3.21,5.80,.22)
    left=-14;bay=5.52;step=3.02;tops=[13,11,9,6,3];base=3.88
    for i,n in enumerate(tops):
        xx=left+(i+.5)*bay;zt=base+n*step
        B(s,WALL,xx,0,base,bay,11.50,n*step)
        for k in range(n):
            zz=base+k*step;win(xx,-5.75,zz+.39,4.62,2.24,4,i+k)
            B(b,SNOW,xx,-6.06,zz,bay-.03,2.11,.19,.038)
            B(b,ACC,xx,-7.04,zz+.18,bay-.23,.14,.48,.022)
            fence(b,xx,-7.04,zz+.65,bay-.26,.43,DARK)
            # Adjustable privacy blades move from side to side between storeys.
            dx=xx+(1 if (i+k//2)%2 else -1)*1.81
            for j in (-1,0,1):B(b,TIM,dx+j*.27,-6.55,zz+.19,.103,.84,2.82)
            with frame(xx,5.75,180):win(0,0,zz+.87,3.92,1.55,3,i+k)
            if i == len(tops)-1 or k >= tops[i+1]:
                with frame(xx+bay/2,0,90):
                    for yy in (-3,2.61):win(yy,0,zz+.72,3.64,1.77,3,k)
        B(s,SNOW,xx,-.43,zt,bay+.05,13.35,.26,.045)
        for y in (-6.97,6.1):B(s,ACC,xx,y,zt+.26,bay,.19,.79)
        B(s,ACC,xx+bay/2-.11,-.45,zt+.26,.22,13.20,.79)
        for yy in (-4.77,.84,3.99):terrace_tree(xx+.39,yy,zt+.26,.86+.16*(i%2))
    # Fluted service core anchors the tall end and carries a projecting rain cap.
    ztop=base+13*step
    B(s,ACC,-13.36,.2,base,2.15,7.09,13*step+1.45,.10)
    for j in range(9):B(s,SNOW,-14.48,-2.86+j*.75,base+.39,.29,.155,13*step+.69,.025)
    for x in (-13.99,-12.74):B(s,SEC,x,0,ztop+1.45,.23,5.66,1.65)
    B(s,SNOW,-13.35,0,ztop+3.10,3.04,7.94,.27,.05)
    for a in (-1,1):plant('Entry planters',a*8,-6.67,.26,.59)


