import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import {validateBytes} from 'gltf-validator';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {Box3,Raycaster,Vector3} from 'three';
const id='public-bus-fold-out-boarding-ramp-cutaway';
const bytes=await readFile(process.argv[2]??new URL('./exports/'+id+'.glb',import.meta.url));
const gltf=JSON.parse(bytes.subarray(20,20+bytes.readUInt32LE(12)));
const k=await validateBytes(new Uint8Array(bytes),{uri:id+'.glb'});
for(const value of ['numErrors','numWarnings','numInfos','numHints'])assert.equal(k.issues[value],0,JSON.stringify(k.issues));
assert.deepEqual(gltf.buffers.map(x=>x.uri),[undefined]);
assert.equal(gltf.images?.length??0,0);
assert.equal(gltf.animations?.length??0,0);
assert.equal(gltf.cameras?.length??0,0);
const g=await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'');
const model=g.scene;model.updateMatrixWorld(true);
const m=(pref)=>{const nodes=[];model.traverse(n=>{if(n.isMesh&&n.name.startsWith(pref))nodes.push(n)});return nodes};
const names=['PUBLIC_BUS_BOARDING_SECTION','CURB_AND_APPROACH_DATUM','ORIGINAL_GENERIC_BUS_DOORWAY_CUTAWAY','DEPLOYED_BOARDING_BRIDGE_AND_SILL'];
assert.ok(names.every(x=>model.getObjectByName(x)),names.join(' '));
const surfaces=['Solid_continuous_interior_floor','Flush_elastomer-colored_heel_transition','One_continuous_sloped_boarding_deck','Physical_toe_join','Center_curb_segment'].flatMap(m);
assert.ok(surfaces.length>=5);
const direction=new Vector3(0,-1,0);
const height=y=>y<-.880?.1906:y>=.18?.445:.445+.24*(y-.18);
let n=0,maxError=0;
const yy=[...Array.from({length:198},(_,i)=>-1.29+.0095*i),...[-.942,-.880,.150,.190].flatMap(q=>[-.00033,-.00009,.00009,.00031].map(e=>q+e))];
for(const y of yy)for(const x of [-.418,-.280,-.120,0,.120,.28,.417]){
 const h=new Raycaster(new Vector3(x,.67,-y),direction).intersectObjects(surfaces,false)[0];
 assert.ok(h,[x,y].join(','));
 const e=Math.abs(h.point.y-height(y)); assert.ok(e<2e-6,[x,y,e].join(','));
 n++; maxError=Math.max(maxError,e);
}
const pivot=m('HINGE_STEEL_PIN_UNBROKEN_ACROSS_ALL_BARRELS');
assert.equal(pivot.length,1);
assert.equal(m('Leaf_physical_hinge_barrel').length,4);
assert.equal(m('Sill_physical_hinge_barrel').length,3);
const b=new Box3().setFromObject(pivot[0],true);
assert.ok(Math.abs(b.min.x+.435)<2e-7&&Math.abs(b.max.x-.435)<2e-7);
assert.equal(m('Continuous_raised_side_guide_edge').length,2);
assert.equal(g.animations.length,0);
const bounds=new Box3().setFromObject(model,true);
assert.ok(bounds.min.y>=0&&bounds.max.y>1.84&&bounds.max.y<1.855);
const q=k.info;
console.log(JSON.stringify({sha256:createHash('sha256').update(bytes).digest('hex'),bytes:bytes.length,issues:k.issues,triangles:q.totalTriangleCount,vertices:q.totalVertexCount,drawCalls:q.drawCallCount,meshes:gltf.meshes.length,materials:gltf.materials.length,continuousSurfaceRays:n,maximumObservedError_m:maxError,staticNodes:gltf.nodes.length,bounds:[bounds.min.toArray(),bounds.max.toArray()]},null,2));
