def build():
    palette('eee4cd','ad5547','638d8a','88948e','685a47')
    s='Residential wings'; t='Open void deck'; g='Rainbow portal'; r='Service roofs'
    B(t,PAVE,0,0,0,38.6,14.9,.20,.06)
    # Two banks of units on pilotis, joined above a three-storey-high passage.
    for side in (-1,1):
        x=side*11.75
        B(s,WALL,x,.05,3.4,14.5,11.6,17.4)
        B(t,SEC,side*16,.8,.20,2.5,6.3,3.2)
        door(side*16,-2.36,.20,1.55,2.45)
        for xx in (side*5.1,side*11.7,side*18.4):
            for yy in (-5.2,5.25):
                B(t,WALL,xx,yy,.20,.62,.70,3.20,.035)
                B(t,ACC,xx,yy,.20,.69,.77,.76,.025)
    # The soffit follows the same ellipse as the enamel bands on both façades.
    arc=[(4.52*math.cos(math.pi*i/32),3.4+7.5*math.sin(math.pi*i/32)) for i in range(33)]
    prism(g,WALL,arc+[(-4.52,12.1),(4.52,12.1)],-5.75,5.85)
    B(s,WALL,0,.05,12.1,9.0,11.6,8.70)
    for yy in (-5.95,5.76):
        for j,m in enumerate((ACC,SUN,SEC)):
            archband(g,m,0,yy-.025*j,3.4,4.50+j*.33,7.50+j*.33,.34,.23,n=36)
            for side in (-1,1): B(g,m,side*(4.67+j*.33),yy+.08-.025*j,.20,.34,.29,3.2)
    for i in range(6):
        z=3.4+2.9*i
        for x,w in ((-11.76,14.48),(11.76,14.48)) if i<3 else ((0,38),):
            B(s,SNOW,x,-5.84,z,w,.52,.22,.018)
            B(s,SEC,x,6.24,z,w,1.05,.18)
            B(s,WALL,x,6.67,z+.18,w,.16,.80)
            B(s,SEC,x,6.68,z+.98,w,.23,.12)
        for side in (-1,1):
            for k,xx in enumerate((7.35,11.9,16.3)):
                x=side*xx
                win(x,-5.755,z+.84,3.31,1.41,3,i//2+k,SEC)
                with frame(0,5.86,180): win(x,0,z+.91,2.55,1.22,2,i+k)
            with frame(side*19,.05,90*side):
                for k in (-3.22,2.66): win(k,0,z+.86,2.52,1.35,2,i)
        if i>=3:
            for x in (-2.13,2.13): win(x,-5.76,z+.84,3.01,1.41,3,i,ACC)
            B(g,ACC,0,-5.83,z,.41,.28,2.9)
    B(r,SEC,0,.05,20.8,38.52,12.22,.34,.04); coping(0,.05,21.14,38.38,12.13)
    for x in (-12.3,12.3):
        B(r,SEC,x,.45,21.14,5.5,4.4,1.94,.04); B(r,SNOW,x,.45,23.08,5.88,4.8,.21,.035)
        for i in range(7): B(r,DARK,x+(i-3)*.50,-1.80,21.73,.31,.12,.72)
    with frame(19.01,0,90):
        B(g,ACC,0,-.04,13.1,2.68,.20,6.65); label('87',0,-.16,17.63,2.22,1.60); label('BLOK',0,-.16,15.85,1.96,.51)
    for x in (-8.5,8.5):
        B(t,ACC,x,-6.34,.2,3.22,.82,.49,.08); B(t,TIM,x,-6.34,.69,3.4,.94,.12,.035)


