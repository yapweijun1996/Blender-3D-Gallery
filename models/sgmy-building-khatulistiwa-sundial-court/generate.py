def build():
    s='Solar Hour Bow'; f='Meridian Frame'; p='Compass Pavement'; a='Promenade'; n='Dial Inscriptions'
    bronze=material('Antique maritime bronze','987044',.34,.46); gold=material('Satin brass highlights','d7a652',.30,.48); jade=material('Verdigris bronze','3a8078',.43,.32); paving=material('Pearl limestone','e3d6b8'); black=material('Midnight granite','344e56',.43,.13); red=material('Ironstone tesserae','ac624a')
    pad(a,0,0,21.4,18.8,sand,rock)
    for z,r1,r2,h,m in ((.30,7.83,7.83,.18,black),(.48,7.69,7.53,.16,paving),(.64,6.64,6.58,.08,bronze),(.72,6.39,6.39,.05,paving)):
        lathe(p,m,0,0,[(z,r1),(z+h,r2)],80)
    for j in range(16):
        t=TAU*j/16;r=5.94 if j%4==0 else 4.9 if j%2==0 else 3.72
        def rose(d,w):return (d*math.sin(t)+w*math.cos(t),d*math.cos(t)-w*math.sin(t),.783)
        for side in (-1,1):skin(p,black if side==1 else red,[rose(.22,0),rose(1.70,.83*side),rose(r,0)],.009)
    # The polar style points nearly horizontal, as appropriate close to the equator.
    tilt=math.radians(2.2); zc=7.68
    def q(ang,r,d):
        a=math.radians(ang);h=-math.cos(a)*r
        return (math.sin(a)*r,d*math.cos(tilt)-h*math.sin(tilt),zc+h*math.cos(tilt)+d*math.sin(tilt))
    def band(mat,ri,ro,front,back,lo,hi,pieces):
        for i in range(pieces):
            a,b=lo+(hi-lo)*i/pieces,lo+(hi-lo)*(i+1)/pieces
            loft(s,mat,[[q(u,ri,front),q(u,ro,front),q(u,ro,back),q(u,ri,back)] for u in (a,b)])
    band(jade,5.57,6.68,-.56,.56,-112,112,72)
    for d in (-.57,.50):
        band(gold,5.54,5.72,d,d+.07,-112.4,112.4,72);band(bronze,6.55,6.75,d,d+.07,-112.4,112.4,72)
    for j in range(-24,25):
        u=j*3.75; hi=6.39 if j%4==0 else 6.1 if j%2==0 else 5.91
        line(n,gold,q(u,5.68,-.58),q(u,hi,-.58),.073 if j%4==0 else .041)
    for j in range(-6,7,2):
        pos=q(j*15,6.36,-.61);sign(n,ivory,str(12+j).zfill(2),pos,.52,.32)
    for sy in (-1,1):
        # Two splayed pairs of supports stop below the style, exposing its shadow path.
        for sx in (-1,1):
            xx,yy=sx*1.88,sy*2.55
            block(f,black,xx,yy,.77,1.25,1.27,.38,.095)
            loft(f,bronze,[[(xx+dx*.55,yy+dy*.55,1.15) for dx,dy in ((-1,-1),(1,-1),(1,1),(-1,1))],[(dx*.23,sy*1.03+dy*.23,zc-.07) for dx,dy in ((-1,-1),(1,-1),(1,1),(-1,1))]])
        pipe(f,jade,q(0,0,sy*.67),q(0,0,sy*1.73),.29,24)
    pipe(f,gold,q(0,0,-3.94),q(0,0,3.68),.145,24)
    tip=Vector(q(0,0,4.62));tail=Vector(q(0,0,3.65));vec=(tip-tail).to_track_quat('Z','Y').to_matrix();loft(f,gold,[[v+vec@Vector((r*math.cos(TAU*i/16),r*math.sin(TAU*i/16),0)) for i in range(16)] for v,r in ((tail,.34),(tip,.025))])
    block(f,black,0,0,.77,3.13,2.04,.55,.12)
    for side in (-1,1):
        for y in (-4.45,.03,4.50):
            x=side*8.33
            for dy in (-.94,.94):block(a,rock,x,y+dy,.30,.62,.35,.40)
            block(a,paving,x,y,.70,.90,2.64,.18,.074)
    block(n,black,0,-7.73,.34,7.25,.67,1.10,.085);plaque(n,bronze,ivory,'D A T A R A N   K H A T U L I S T I W A',0,-8.10,.93,6.88,.69)


