def bolster(name,x,levels,m,group='Upholstery'):
    # Stacked rounded rectangular sections allow both recline and a crowned cushion.
    rings=[[(a,b,z) for a,b in rounded(w,d,min(r,w*.495,d*.495),(x,y),6)] for z,y,w,d,r in levels]
    n=len(rings[0]); faces=[tuple(reversed(range(n))),tuple(range(n*(len(rings)-1),n*len(rings)))]
    for j in range(len(rings)-1):
        for i in range(n):
            k=(i+1)%n; faces.append((j*n+i,j*n+k,(j+1)*n+k,(j+1)*n+i))
    return mesh(name,[v for row in rings for v in row],faces,m,group=group,smooth=True)
