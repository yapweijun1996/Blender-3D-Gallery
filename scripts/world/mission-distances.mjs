// Road distances between the mission places (and the start), by the shortest drivable path on the mapped network.
// Writes src/world/mission-distances.js. Run after changing the tiles or the missions: node scripts/world/mission-distances.mjs
import fs from "node:fs";
import { MISSIONS } from "../../src/world/missions.js";
import { buildTrafficGraph } from "../../src/world/traffic.js";

const tilesDir = new URL("../../models/world/tiles/", import.meta.url);
const tiles = fs.readdirSync(tilesDir).filter(name => name !== "index.json").sort().map(name => JSON.parse(fs.readFileSync(new URL(name, tilesDir), "utf8")));
const graph = buildTrafficGraph(tiles);

// Directed graph over road edges' end nodes; a place joins the network at the nearest point of the nearest edge.
const START = { id: "start", x: -61, z: -12 };
const places = [START, ...MISSIONS];
const links = new Map(); // node -> [{ to, length }]
const link = (from, to, length) => (links.get(from) ?? links.set(from, []).get(from)).push({ to, length });
for (const edge of graph.edges.values()) {
  link(edge.from, edge.to, edge.length);
  if (!edge.oneway) link(edge.to, edge.from, edge.length);
}
function snap(place) {
  let best = null;
  for (const edge of graph.edges.values()) {
    for (let i = 1; i < edge.points.length; i++) {
      const a = edge.points[i - 1], b = edge.points[i], sx = b[0] - a[0], sz = b[1] - a[1], span = sx * sx + sz * sz || 1;
      const t = Math.max(0, Math.min(1, ((place.x - a[0]) * sx + (place.z - a[1]) * sz) / span));
      const distance = Math.hypot(place.x - (a[0] + sx * t), place.z - (a[1] + sz * t));
      if (!best || distance < best.distance) best = { distance, edge, along: edge.cumulative[i - 1] + t * Math.sqrt(span) };
    }
  }
  return best;
}
function dijkstra(sources) {
  const dist = new Map(sources.map(source => [source.node, source.cost]));
  const queue = [...dist.entries()];
  while (queue.length) {
    queue.sort((a, b) => a[1] - b[1]);
    const [node, cost] = queue.shift();
    if (cost > dist.get(node)) continue;
    for (const { to, length } of links.get(node) ?? []) {
      const next = cost + length;
      if (next < (dist.get(to) ?? Infinity)) { dist.set(to, next); queue.push([to, next]); }
    }
  }
  return dist;
}

const snapped = places.map(place => ({ place, ...snap(place) }));
const table = {};
for (const from of snapped) {
  // Leaving from the middle of an edge: forward to its end node (and back to its start node when the road is two-way).
  const sources = [{ node: from.edge.to, cost: from.edge.length - from.along }];
  if (!from.edge.oneway) sources.push({ node: from.edge.from, cost: from.along });
  const dist = dijkstra(sources);
  table[from.place.id] = {};
  for (const to of snapped) {
    if (to === from) continue;
    // Arriving on an edge: from its start node, or from its end node when two-way.
    const options = [(dist.get(to.edge.from) ?? Infinity) + to.along];
    if (!to.edge.oneway) options.push((dist.get(to.edge.to) ?? Infinity) + (to.edge.length - to.along));
    const road = Math.min(...options);
    const straight = Math.hypot(to.place.x - from.place.x, to.place.z - from.place.z);
    // Places on the same edge, or no connection found: fall back to a typical detour factor.
    table[from.place.id][to.place.id] = Number.isFinite(road) ? Math.round(Math.max(road, straight)) : Math.round(straight * 1.3);
  }
}
const output = `// Generated by scripts/world/mission-distances.mjs: shortest drivable road distance in metres from a place to each mission.\nexport const ROAD_DISTANCES = ${JSON.stringify(table, null, 2)};\n`;
const target = new URL("../../src/world/mission-distances.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== output) {
    throw new Error("Mission distances are stale. Run node scripts/world/mission-distances.mjs to update them.");
  }
  console.log("Mission distances match the shipped road network.");
} else {
  fs.writeFileSync(target, output);
  console.log(JSON.stringify(table, null, 1));
}
