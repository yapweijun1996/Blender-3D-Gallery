import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';
import { buildFortCanningTunnel, readPinnedFortCanningTunnel } from './fort-canning-tunnel.mjs';

const route = await readPinnedFortCanningTunnel();
const generated = new URL('./fort-canning-tunnel.json', import.meta.url);
const flatten = groups => groups.flatMap((points, index) => index ? points.slice(1) : points);
const tunnel = flatten(route.fragments.map(fragment => fragment.points));

test('Fort Canning Link route is generated byte-for-byte from the tracked, attributed snapshot', async () => {
  assert.equal(await readFile(generated, 'utf8'), JSON.stringify(route) + '\n');
  assert.deepEqual(route.source, {
    osmWayId: 159677768,
    edgeId: '159677768:0',
    tunnelTag: 'yes',
    osmLayer: -1,
    locationNote: 'Estimated location ???',
    timestamp: '2026-11-20T12:18:15Z',
    attribution: '© OpenStreetMap contributors (ODbL)',
    fixtureSha256: '297a9877428e2cf9714cf414f414f07586d383d1bd17dfec7fd2749a9bfaa998',
  });
  assert.equal(route.name, 'Fort Canning Link');
  assert.equal(route.oneway, true);
  assert.equal(route.lanes, 3);
  assert.equal(route.width, 10.2);
  assert.equal(route.length, 360.916499);
});

test('covered roads and building passages cannot stand in for the pinned underground road', () => {
  for (const tags of [
    { tunnel: 'building_passage', layer: '-1' },
    { tunnel: 'covered', layer: '-1' },
    { tunnel: 'yes', layer: '-1', covered: 'yes' },
    { tunnel: 'yes', layer: '0' },
  ]) {
    const way = { type: 'way', id: route.source.osmWayId, tags };
    assert.throws(() => buildFortCanningTunnel({ elements: [way] }), /not the pinned underground road/);
  }
});

test('actual surface connections and all three tile pieces share identical boundary section samples', () => {
  const { approaches, fragments, portals } = route;
  assert.deepEqual(portals.map(({ nodeId, surfaceWayId }) => [nodeId, surfaceWayId]), [
    [1717871124, 719635728], [235180402, 39351292],
  ]);
  assert.deepEqual(tunnel[0], portals[0].point);
  assert.deepEqual(tunnel.at(-1), portals[1].point);
  assert.deepEqual(approaches.entry.at(-1), portals[0].point);
  assert.deepEqual(approaches.exit[0], portals[1].point);
  assert.equal(approaches.entry[0].s, -31.097871);
  assert.equal(approaches.exit.at(-1).s, 435.273987);
  assert.ok([...approaches.entry, ...approaches.exit].every(sample => sample.y === 0));
  assert.equal(route.tileSize, 250);
  assert.deepEqual(fragments.map(({ tile }) => tile), [[-6, -6], [-6, -7], [-7, -7]]);
  assert.equal(fragments[0].points.at(-1).z, -1500);
  assert.equal(fragments[0].points.at(-1).s, 229.467055);
  assert.equal(fragments[1].points.at(-1).x, -1500);
  assert.equal(fragments[1].points.at(-1).s, 259.602038);
  for (let i = 1; i < fragments.length; i++) {
    assert.deepEqual(fragments[i].points[0], fragments[i - 1].points.at(-1));
  }
  for (const { tile, points } of fragments) {
    for (const point of points) {
      for (const [axis, name] of ['x', 'z'].entries()) {
        assert.ok(point[name] >= tile[axis] * route.tileSize);
        assert.ok(point[name] <= (tile[axis] + 1) * route.tileSize);
      }
    }
  }
});

test('game ramps are smooth at both portals, stay within 8% and reach the assumed depth', () => {
  const { approaches, length, depth, maxGrade, rampLength } = route;
  assert.equal(depth, 5.5);
  assert.equal(maxGrade, 0.08);
  assert.equal(rampLength, 103.125);
  const startOfBase = tunnel.findIndex(({ s }) => s === rampLength);
  const endOfBase = tunnel.findIndex(({ s }) => Math.abs(s - (length - rampLength)) < 1e-6);
  assert.ok(startOfBase > 0 && endOfBase > startOfBase);
  assert.ok(tunnel.slice(startOfBase, endOfBase + 1).every(({ y }) => y === -depth));
  const path = flatten([approaches.entry, tunnel, approaches.exit]);
  const grade = (a, b) => (b.y - a.y) / (b.s - a.s);
  for (const [index, sample] of path.slice(1).entries()) {
    const previous = path[index];
    const stationStep = sample.s - previous.s;
    assert.ok(stationStep > 0 && stationStep <= 1.000002, `station step ${stationStep} from ${previous.s}`);
    assert.ok(Math.abs(Math.hypot(sample.x - previous.x, sample.z - previous.z) - stationStep) < 0.000004);
    assert.ok(Math.abs(grade(previous, sample)) <= maxGrade + 0.000005);
  }
  for (const [a, b] of [[tunnel[0], tunnel[1]], [tunnel[startOfBase - 1], tunnel[startOfBase]],
    [tunnel[endOfBase], tunnel[endOfBase + 1]], [tunnel.at(-2), tunnel.at(-1)]]) {
    assert.ok(Math.abs(grade(a, b)) < 0.002, `slope discontinuity at station ${a.s}`);
  }
});
